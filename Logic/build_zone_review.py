"""Build Research/SearchZones_Review.md: every search zone and container the randomizer can put
an item in, grouped by room, for the user to describe as a player would recognise it.

  python build_zone_review.py

Rows come from the same data as TatouScenario's F8 colours (Generator/zone_table.py):
  * item spots: the zones holding an item in vanilla (search slots, contact spots, the hidden
    library bookcase) - the spoiler and the walkthrough name these;
  * extra spots: zones empty in vanilla that "Many Search Places" may use (generator v7: only
    user-annotated "Empty searchable area" zones);
  * containers opened through an object (C:N, inspector label "OBJ N").
Descriptions already written in the existing file are kept (matched by zone id).
"""
from __future__ import annotations

import csv
import json
import random
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
GEN = HERE.parent
ROOT = GEN.parent
OUT = ROOT / "Research" / "SearchZones_Review.md"
sys.path.insert(0, str(GEN / "Generator"))
sys.path.insert(0, str(GEN / "Patcher"))

import generate as G          # noqa: E402
import zone_table as Z        # noqa: E402
from aitd_pak import read_pak  # noqa: E402


def existing_descriptions() -> dict[str, str]:
    if not OUT.exists():
        return {}
    out = {}
    for line in OUT.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\| (F\d+:R\d+:HC\d+|C:\d+) ", line)
        if m:
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if cells[-1]:
                out[m.group(1)] = cells[-1]
    return out


def main() -> int:
    objs = G.O.load(G.SRC / "OBJETS.ITD")
    nice = G.friendly_names(objs)
    label = G.location_labels()
    notes = {r["zone_id"]: r["description"].strip() for r in
             csv.DictReader(open(ROOT / "References" / "AITD_zones.csv", encoding="utf-8", errors="replace"))}
    vanilla = {z: items for z, items in Z.vanilla_zones().items() if not z.startswith("OBJ")}
    lives = [G.L.decode(e.data) for e in read_pak(G.SRC / "LISTLIFE.PAK").entries]
    extra = [x["id"] for x in G.extra_spot_slots(random.Random(0), 10 ** 6, lives) if x["id"] not in vanilla]
    acq = json.loads((GEN / "Patcher" / "catalog" / "acquisition_slots.json").read_text(encoding="utf-8"))
    containers = [s for s in acq["slots"] if s["family"] in ("container", "locked_container")]
    keep = existing_descriptions()

    rows: dict[str, list[tuple]] = {}
    def room_of(zone):
        fl, rm = zone.split(":")[:2]
        return f"{fl[1:]}/{rm[1:]}"
    for z, items in vanilla.items():
        rows.setdefault(room_of(z), []).append((0, z, "item spot", "vanilla: " + ", ".join(nice[i] for i in items)))
    for z in extra:
        rows.setdefault(room_of(z), []).append((1, z, "extra spot", "empty in vanilla"))
    for c in containers:
        loc = c["location"]
        owner = c["owners"][0]
        kind = "locked container" if c["family"] == "locked_container" else "container"
        rows.setdefault(f"{loc['floor']}/{loc['room']}", []).append(
            (2, c["slot_id"], kind, f"F8 label OBJ {owner}; vanilla: " + ", ".join(nice[i] for i in c["items"])))

    def room_key(r):
        a, b = r.split("/")
        return (int(a), int(b) if b.isdigit() else 99)
    n_item = sum(1 for v in rows.values() for r in v if r[0] == 0)
    n_extra = sum(1 for v in rows.values() for r in v if r[0] == 1)
    n_cont = sum(1 for v in rows.values() for r in v if r[0] == 2)
    lines = [
        "# Search zones: descriptions for the spoiler",
        "",
        "Every place the randomizer can put an item in, by room. Please describe each one in the last "
        "column as a player would recognise it (e.g. \"bookcase left of the door\", \"under the bed\"). "
        "The spoiler and walkthrough will show your description instead of the zone id.",
        "",
        f"- **Item spots** ({n_item}): hold an item in vanilla; every seed uses them.",
        f"- **Extra spots** ({n_extra}): empty in vanilla; only the \"Many Search Places\" option uses them "
        "(only zones you marked \"Empty searchable area\", generator v7).",
        f"- **Containers** ({n_cont}): opened through an object; the F8 inspector shows them as the `OBJ n` label.",
        "- Zone ids are the F8 inspector's labels. *Your note* is what you wrote in the inspector review "
        "(`References/AITD_zones.csv`), if anything. Leave a description empty if you can't tell; the "
        "spoiler then keeps the id.",
        "- Generated by `Generated/Logic/build_zone_review.py`; rerunning it keeps the descriptions you wrote.",
    ]
    for room in sorted(rows, key=room_key):
        lines += ["", f"## {label(room)} ({room})", "",
                  "| Zone | Kind | Contents | Your note | Description |", "|---|---|---|---|---|"]
        for _, z, kind, contents in sorted(rows[room]):
            note = notes.get(z, "").replace("|", "/").replace("\n", " ") if not z.startswith("C:") else ""
            lines.append(f"| {z} | {kind} | {contents} | {note} | {keep.get(z, '')} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT}: {n_item} item spots, {n_extra} extra spots, {n_cont} containers, "
          f"{len(rows)} rooms, {len(keep)} descriptions kept")
    return 0


if __name__ == "__main__":
    sys.exit(main())
